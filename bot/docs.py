def to_html_chunks(title: str, blocks: list[Block], footer: str = "",
                   limit: int = 3800) -> list[str]:
    """Сообщения Telegram (HTML), каждое не длиннее limit символов."""
    parts = [f"<b>{html.escape(title)}</b>"]
    for kind, text in blocks:
        parts.append(f"\n<b>{html.escape(text)}</b>" if kind == "h" else html.escape(text))
    if footer:
        parts.append("\n" + footer)
    chunks, cur = [], ""
    for part in parts:
        if cur and len(cur) + 1 + len(part) > limit:
            chunks.append(cur)
            cur = part.lstrip("\n")
        else:
            cur = f"{cur}\n{part}" if cur else part
    if cur:
        chunks.append(cur)
    return chunks


def to_telegraph(blocks: list[Block]) -> list[dict]:
    """Содержимое страницы telegra.ph (формат Node)."""
    return [{"tag": "h3" if kind == "h" else "p", "children": [text]} for kind, text in blocks]
