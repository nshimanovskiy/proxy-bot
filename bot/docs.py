async def prices(shop: Shop, c: DocContext, tz=None) -> tuple[str, list[Block]]:
    """Актуальные цены прямо из каталога Steel Proxy с вашей наценкой."""
    now = datetime.now(tz).strftime("%d.%m.%Y %H:%M") if tz else datetime.now().strftime("%d.%m.%Y")
    blocks: list[Block] = [
        ("p", f"Актуально на {now}. Цены в рублях за 1 прокси на указанный срок. Итоговая сумма "
              "заказа (цена × количество) показывается до оплаты."),
    ]
    for t in await shop.proxy_types():
        locs = await shop.locations(t["code"])
        rows = []
        for loc in locs:
            terms_ = []
            for d in loc.term_options:
                p = await shop.unit_sell_price(loc.proxy_type, loc.node_id, d)
                if p is not None:
                    terms_.append(f"{term_label(d)} — {fmt_rub(p)}")
            if terms_:
                rows.append(((loc.country_code, loc.title), terms_))
        if not rows:
            continue
        blocks.append(("h", PROXY_TYPE_TITLES.get(t["code"], t.get("title") or t["code"])))
        names = locations.display_many([k for k, _ in rows])
        for name, (_, terms_) in sorted(zip(names, rows), key=lambda x: x[0].split(" ", 1)[-1]):
            blocks.append(("p", f"{name}: " + "; ".join(terms_)))

    blocks += [
        ("h", "Что входит в стоимость"),
        ("p", "• Выделенный прокси в выбранной стране на весь оплаченный срок."),
        ("p", "• Подключение по HTTP и SOCKS5, логин и пароль; данные выдаются сразу после оплаты."),
        ("p", "• Напоминание за сутки до окончания срока и поддержка."),
        ("h", "Оплата"),
        ("p", f"Заказы оплачиваются с внутреннего баланса. Баланс пополняется в разделе "
              f"«💰 Баланс», минимальная сумма — {c.min_topup_rub} ₽. Скрытых платежей, подписок и "
              "автоматических списаний нет."),
        ("h", "Продление"),
        ("p", "Заказ можно продлить на 1, 2, 3 или 6 месяцев в разделе «📦 Мои заказы» по цене "
              "месячного тарифа локации, умноженной на число месяцев и количество прокси."),
        ("h", "Возврат"),
        ("p", "Условия возврата — в разделе 4 Пользовательского соглашения (команда /terms)."),
    ]
    return "Цены и тарифы", blocks


