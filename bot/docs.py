# Дата текущей редакции текстов. Меняйте (или задайте DOCS_DATE в .env), когда правите документы.
DOCS_REVISION = "17.10.2026"

Block = tuple[str, str]

PROXY_TYPE_TITLES = {"server": "Серверные прокси", "residential": "Резидентские прокси"}


@dataclass(frozen=True)
class DocContext:
    shop_name: str
    bot_username: str
    operator_name: str
    operator_inn: str
    support_contact: str
    support_email: str
    min_topup_rub: int
    date: str = DOCS_REVISION

    @classmethod
    def from_config(cls, cfg, bot_username: str) -> "DocContext":
        return cls(shop_name=cfg.shop_name, bot_username=bot_username.lstrip("@"),
                   operator_name=cfg.operator_name, operator_inn=cfg.operator_inn,
                   support_contact=cfg.support_contact, support_email=cfg.support_email,
                   min_topup_rub=cfg.min_topup_rub, date=cfg.docs_date or DOCS_REVISION)

    # ---------- части текста ----------
    @property
    def service(self) -> str:
        return f"Telegram-бот «{self.shop_name}» (@{self.bot_username})"

    @property
    def operator(self) -> str:
        name = self.operator_name or "[укажите OPERATOR_NAME в .env]"
        return f"{name}, ИНН {self.operator_inn}" if self.operator_inn else name

    @property
    def contacts(self) -> str:
        parts = [f"Telegram — {self.support_contact}"] if self.support_contact else []
        if self.support_email:
            parts.append(f"e-mail — {self.support_email}")
        parts.append("обращение в боте — «🆘 Поддержка» → «Написать в поддержку»")
        return "; ".join(parts)

    def missing(self) -> list[str]:
        """Каких данных не хватает, чтобы документы можно было показать банку."""
        out = []
        if not self.operator_name:
            out.append("OPERATOR_NAME (ФИО / ИП / организация — как в договоре с банком)")
        if not self.support_email and not self.support_contact.startswith("@"):
            out.append("SUPPORT_CONTACT (@username) или SUPPORT_EMAIL")
        return out


